"""Backend contract. All writes must use the supplied loop-owned output directory."""
from typing import Protocol


class BenchmarkAdapter(Protocol):
    protocol: str

    def discover(self) -> list[dict]: ...
    def baseline_summary(self, group: dict) -> dict: ...
    def checkpoints(self, group: dict) -> list[dict]: ...
    def raw_files(self, group: dict, rounds: list[dict]) -> list[str]: ...
    def episodes(self, feedback: str, seeds: list[int]) -> list[dict]: ...
    def curve(self, group: dict, train_dir: str | None = None) -> dict: ...
    def facts(self, group: dict, artifact_id: str, feedback: str, seeds: list[int], train_dir: str) -> dict: ...
    def validate_training_data(self, group: dict, ids: list[int]) -> list[str]: ...
    def train(self, group: dict, artifact: dict, request: dict, output: str, *, save_at_steps: list[int] | None = None) -> dict: ...
    def evaluate(self, group: dict, artifact: dict, seeds: list[int], output: str) -> dict: ...


class DemonstrationRepairAdapter(BenchmarkAdapter, Protocol):
    """Optional capability; LIBERO must implement it on its own server."""
    def demonstration_files(self, group: dict) -> list[str]: ...
    def demonstrations(self, group: dict) -> list[dict]: ...
    def prepare_repairs(self, group: dict, intents: list[dict], folder: str, parent: str | None = None) -> str: ...
    def accepted_repairs(self, session: str) -> dict[int, str]: ...
    def create_dataset_version(self, group: dict, ids: list[int], replacements: dict | None = None, parent: str | None = None) -> str: ...
    def try_repair(self, session: str, demo_id: int, patch: dict) -> dict: ...
    def verify_repair(self, session: str, demo_id: int, candidate: str) -> dict: ...
